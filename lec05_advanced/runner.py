def _terminate(process):
    if process.poll() is not None:
        return
    try:
        if os.name == "posix":
            os.killpg(process.pid, signal.SIGTERM)
        else:
            process.terminate()
    except ProcessLookupError:
        return
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:
        try:
            if os.name == "posix":
                os.killpg(process.pid, signal.SIGKILL)
            else:
                process.kill()
        except ProcessLookupError:
            pass
        process.wait()


def _run_attempt(root, worker_path, experiment_dir, job, model, attempt):
    attempts = experiment_dir / "attempts"
    stem = job["trial_id"] + f"__a{attempt:03d}"
    json_path = attempts / (stem + ".json")
    log_path = attempts / (stem + ".txt")
    job_path = attempts / (stem + ".job.json")
    request = {**job, "model": model, "attempt": attempt, "started_utc": _utc_now()}
    _write_json(job_path, request)
    environment = os.environ.copy()
    environment["AIE_MODEL"] = model
    environment["AIE_TREE_PREVIEW"] = "improved" if job["mode"] == "tree_improved" else "original"
    environment["PYTHONUNBUFFERED"] = "1"
    process = None
    forced_error = None
    attempt_started = time.perf_counter()
    with log_path.open("w", encoding="utf-8") as log:
        try:
            process = subprocess.Popen(
                [sys.executable, str(worker_path), str(root), str(job_path), str(json_path)],
                cwd=root, env=environment, stdout=log, stderr=subprocess.STDOUT,
                start_new_session=(os.name == "posix"),
            )
            process.wait(timeout=TRIAL_TIMEOUT_SECONDS)
        except subprocess.TimeoutExpired:
            _terminate(process)
            forced_error = {"status": "timeout", "error": f"{TRIAL_TIMEOUT_SECONDS}秒で打ち切りました。"}
        except KeyboardInterrupt:
            if process is not None:
                _terminate(process)
            _write_json(json_path, {**request, "status": "interrupted", "error": "ユーザーが中断しました。", "http_status": None})
            raise
        except OSError as error:
            forced_error = {"status": "failed", "error": str(error)}
    if forced_error:
        _write_json(json_path, {**request, **forced_error, "http_status": None})
    if not json_path.is_file():
        _write_json(json_path, {**request, "status": "failed", "http_status": None, "error": "結果JSONが作成されませんでした。対応するtxtログを確認してください。"})
    result = _read_json(json_path)
    if process is not None and process.returncode and result.get("status") == "success":
        result.update(status="failed", error="計測後に子プロセスが異常終了しました。", http_status=None)
    result.update(
        finished_utc=_utc_now(), attempt_wall_seconds=time.perf_counter() - attempt_started,
        process_return_code=process.returncode if process is not None else None,
    )
    _write_json(json_path, result)
    return result


def make_bundle(root, experiment_dir):
    """Explicit allowlist only: no credentials, database, .git, or environment dumps."""
    root, experiment_dir = Path(root).resolve(), Path(experiment_dir).resolve()
    experiment_dir.relative_to(root)
    bundle_path = root / "lec05_results.zip"
    extra = [
        root / "lec05_advanced/run.py", root / "lec05_advanced/runner.py",
        root / "lec05_advanced/tree_preview.py", root / "lec05_advanced/cases.json",
        root / "lec05_advanced/retrieval_original.py", root / "lec05_advanced/README.md",
        root / "app/tree_preview.py", root / "app/retrieval.py",
        root / "app/tools.py", root / "app/agent.py",
        root / "lectures/05/logs/rag_before.txt", root / "lectures/05/logs/tree_before.txt",
        root / "lectures/05/advanced_design/offline_check.json",
        root / "lectures/05/advanced_design/cases.json",
        root / "lectures/05/advanced_backup/retrieval_before.py.txt",
    ]
    entries = [path for path in experiment_dir.rglob("*") if path.is_file() and path.suffix in {".json", ".txt", ".csv", ".md"}]
    entries.extend(path for path in extra if path.is_file())
    with ZipFile(bundle_path, "w", ZIP_DEFLATED) as archive:
        for path in sorted(set(entries)):
            archive.write(path, path.relative_to(root).as_posix())
    return bundle_path


def run_comparison(root, cases, model="gemini-3.5-flash-lite", repeats=2, selected_ids=None):
    root = Path(root).resolve()
    _validate_cases(cases)
    if not isinstance(repeats, int) or not 1 <= repeats <= 5:
        raise ValueError("repeatsは1〜5を指定してください。")
    if selected_ids is not None:
        unknown = set(selected_ids) - {case["id"] for case in cases}
        if unknown:
            raise ValueError("不明な質問ID: " + ", ".join(sorted(unknown)))
        cases = [case for case in cases if case["id"] in selected_ids]
    if not cases:
        raise ValueError("比較する質問がありません。")
    inputs = _manifest_inputs(root, cases, model, repeats)
    canonical = json.dumps(inputs, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    fingerprint = hashlib.sha256(canonical.encode()).hexdigest()
    experiment_dir = root / "lectures/05/advanced_results" / fingerprint[:16]
    experiment_dir.mkdir(parents=True, exist_ok=True)
    (experiment_dir / "attempts").mkdir(exist_ok=True)
    manifest_file = experiment_dir / "manifest.json"
    if manifest_file.exists():
        manifest = _read_json(manifest_file)
        if manifest.get("fingerprint") != fingerprint or manifest.get("inputs") != inputs:
            raise RuntimeError("保存済みの条件と一致しないため、再開を停止しました。")
    else:
        manifest = {"fingerprint": fingerprint, "created_utc": _utc_now(), "inputs": inputs}
        _write_json(manifest_file, manifest)
    worker_dir = root / ".cache/lec05"
    worker_dir.mkdir(parents=True, exist_ok=True)
    worker_path = worker_dir / ("worker_" + hashlib.sha256(WORKER_SOURCE.encode()).hexdigest()[:12] + ".py")
    worker_path.write_text(WORKER_SOURCE, encoding="utf-8")
    jobs = _schedule(cases, repeats)
    successful = _successful_results(experiment_dir, jobs, model)
    _write_reports(experiment_dir, manifest, cases, jobs, successful)
    print(f"比較開始：{len(cases)}問 × 3方式 × {repeats}回 = {len(jobs)}試行。保存済み成功：{len(successful)}", flush=True)
    print(f"モデル：{model}。回答の品質は実行後に本文と照合して評価します。", flush=True)
    try:
        for number, job in enumerate(jobs, 1):
            if job["trial_id"] in successful:
                print(f"[{number:02d}/{len(jobs)}] {job['case_id']} / {MODE_LABELS[job['mode']]} / {job['repeat']}回目：保存済み", flush=True)
                continue
            prior = list((experiment_dir / "attempts").glob(job["trial_id"] + "__a*.json"))
            numbers = [int(match.group(1)) for path in prior if (match := re.search(r"__a(\d+)\.json$", path.name))]
            first_attempt = max(numbers, default=0) + 1
            for retry in range(MAX_ATTEMPTS_PER_INVOCATION):
                attempt = first_attempt + retry
                print(f"[{number:02d}/{len(jobs)}] {job['case_id']} / {MODE_LABELS[job['mode']]} / {job['repeat']}回目：実行中（試行{attempt}）", flush=True)
                result = _run_attempt(root, worker_path, experiment_dir, job, model, attempt)
                if result.get("status") == "success":
                    print(f"  完了：{result['elapsed_seconds']:.2f}秒、入力{result['input_tokens']:,}、モデル応答{result['model_responses']}回", flush=True)
                    break
                code = result.get("http_status")
                if code in TRANSIENT_CODES and retry + 1 < MAX_ATTEMPTS_PER_INVOCATION:
                    delay = 30 * (retry + 1)
                    print(f"  API一時エラー HTTP {code}。{delay}秒後に同じ条件で再試行します。", flush=True)
                    time.sleep(delay)
                    continue
                raise RuntimeError(
                    f"{job['case_id']} / {MODE_LABELS[job['mode']]}で停止："
                    f"{result.get('error', result.get('status'))}\n"
                    "成功した試行は保存済みです。同じコマンドで未完了分から再開できます。"
                )
            successful = _successful_results(experiment_dir, jobs, model)
            _write_reports(experiment_dir, manifest, cases, jobs, successful)
            if number < len(jobs):
                time.sleep(2)
    finally:
        successful = _successful_results(experiment_dir, jobs, model)
        _write_reports(experiment_dir, manifest, cases, jobs, successful)
        bundle = make_bundle(root, experiment_dir)
        print(f"結果保存：{experiment_dir.relative_to(root)}", flush=True)
        print(f"確認用ZIP：{bundle.name}（成功 {len(successful)}/{len(jobs)}）", flush=True)
    return experiment_dir
