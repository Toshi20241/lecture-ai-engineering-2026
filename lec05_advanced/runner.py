def _utc_now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
    temp.replace(path)


def _read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _sha(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _validate_cases(cases):
    ids = set()
    for case in cases:
        case_id = case.get("id", "")
        if not re.fullmatch(r"[a-zA-Z0-9_-]+", case_id):
            raise ValueError("質問IDは英数字・_・-だけにしてください。")
        if case_id in ids or not isinstance(case.get("question"), str) or not case["question"].strip():
            raise ValueError("質問IDの重複、または空の質問があります。")
        ids.add(case_id)


def _schedule(cases, repeats):
    """Reverse each pair of repeats, so every method averages position 2 per case."""
    jobs = []
    for repeat in range(1, repeats + 1):
        for index, case in enumerate(cases):
            rotation = (index + (repeat - 1) // 2) % len(MODES)
            order = list(MODES[rotation:] + MODES[:rotation])
            if repeat % 2 == 0:
                order.reverse()
            for mode in order:
                jobs.append({
                    "case_id": case["id"], "question": case["question"],
                    "split": case.get("split", "validation"),
                    "mode": mode, "repeat": repeat,
                    "trial_id": f"{case['id']}__{mode}__r{repeat:02d}",
                })
    return jobs


def _manifest_inputs(root, cases, model, repeats):
    tracked = [
        "app/agent.py", "app/tools.py", "app/retrieval.py", "app/tree_preview.py",
        "app/config.py", "pyproject.toml", "uv.lock",
        "data/rag_data/lectures.json", "data/rag_data/tree.json",
    ]
    source_hashes = {name: _sha(root / name) for name in tracked if (root / name).is_file()}
    db_path = Path(os.environ.get("AIE_RAG_DB", str(root / "data/rag_data/index.sqlite3")))
    if not db_path.is_absolute():
        db_path = root / db_path
    dependencies = {}
    for package in ["pydantic-ai-slim", "google-genai", "sqlite-vec"]:
        try:
            dependencies[package] = importlib.metadata.version(package)
        except importlib.metadata.PackageNotFoundError:
            dependencies[package] = "not-installed"
    return {
        "runner_version": RUNNER_VERSION,
        "runner_sha256": _sha(Path(__file__)),
        "worker_sha256": hashlib.sha256(WORKER_SOURCE.encode()).hexdigest(),
        "model": model, "cases": cases, "repeats": repeats,
        "modes": list(MODES), "source_sha256": source_hashes,
        "search_database_sha256": _sha(db_path) if db_path.is_file() else None,
        "python": sys.version.split()[0], "packages": dependencies,
    }


def _job_matches(result, job, model):
    return all(result.get(key) == job.get(key) for key in ["trial_id", "case_id", "question", "mode", "repeat"]) and result.get("model") == model


def _successful_results(experiment_dir, jobs, model):
    wanted = {job["trial_id"]: job for job in jobs}
    successful = {}
    for path in sorted((experiment_dir / "attempts").glob("*.json")):
        if path.name.endswith(".job.json"):
            continue
        try:
            result = _read_json(path)
        except (OSError, ValueError):
            continue
        job = wanted.get(result.get("trial_id"))
        if job and result.get("status") == "success" and _job_matches(result, job, model):
            result["result_file"] = path.relative_to(experiment_dir).as_posix()
            successful[job["trial_id"]] = result
    return successful


def _average(records, field):
    values = [record.get(field) for record in records]
    if not values or any(value is None for value in values):
        return None
    return mean(values)


def _summary_rows(cases, jobs, successful):
    groups = [(case["id"], case.get("split", "validation"), {case["id"]}) for case in cases]
    for split in ["development", "validation"]:
        ids = {case["id"] for case in cases if case.get("split", "validation") == split}
        if ids:
            groups.append(("ALL_" + split.upper(), split, ids))
    groups.append(("ALL", "all", {case["id"] for case in cases}))
    rows = []
    for group_id, split, ids in groups:
        for mode in MODES:
            planned = [job for job in jobs if job["case_id"] in ids and job["mode"] == mode]
            records = [successful[job["trial_id"]] for job in planned if job["trial_id"] in successful]
            full_page_mean = mean(len(record["full_page_ids"]) for record in records) if records else None
            row = {
                "question_id": group_id, "split": split, "mode": mode,
                "completed": len(records), "planned": len(planned),
                "mean_seconds": _average(records, "elapsed_seconds"),
                "mean_input_tokens": _average(records, "input_tokens"),
                "mean_output_tokens": _average(records, "output_tokens"),
                "mean_model_responses": _average(records, "model_responses"),
                "mean_tool_calls": _average(records, "tool_call_count"),
                "mean_full_pages": full_page_mean,
                "mean_generation_cost_usd": _average(records, "generation_cost_usd"),
                "quality_status": "未評価",
            }
            rows.append(row)
    return rows


def _format(value, digits=2):
    return "未記録" if value is None else f"{value:,.{digits}f}"


